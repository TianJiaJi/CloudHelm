import { copyFile, mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, it, vi } from 'vitest';
import { Type } from 'typebox';
import type { SessionEvent } from '@cloudhelm/core';
import { createConversationSession } from '../../packages/adapters/src/pi-session.js';
import { fixtureMessageText, openAiFixture } from './pi-session-fixture.js';

it.each(['history', 'compacted'])('restores a transcript generated by Pi 0.99.1 (%s) without replay or network', async (kind) => {
  const root = await mkdtemp(join(tmpdir(), 'cloudhelm-pi-upgrade-'));
  const id = `pi-0991-${kind}`;
  const destination = join(root, `${id}.jsonl`);
  const fixture = await openAiFixture(async () => ({ text: 'Continue from the recorded facts without replay.' }));
  let session: Awaited<ReturnType<typeof createConversationSession>> | undefined;
  const events: SessionEvent[] = [];
  const execute = vi.fn(async () => ({ content: [{ type: 'text' as const, text: 'Unexpected replay' }], details: undefined }));
  const beforeRequest = vi.fn();
  try {
    await copyFile(new URL(`./fixtures/${id}.jsonl`, import.meta.url), destination);
    const original = await readFile(destination, 'utf8');
    session = await createConversationSession({
      profile: { provider: 'cloudhelm-custom', modelId: 'fixture', baseUrl: fixture.baseUrl, apiKey: 'synthetic-upgrade-key' },
      storage: { directory: root, id, restore: true }, systemPrompt: 'Backend-authorized synthetic recovery only.',
      tools: [{ name: 'observe', label: 'Observe', description: 'Observe only when explicitly requested',
        parameters: Type.Object({ port: Type.Integer() }), replay: 'never', execute }],
      clarification: { ask: async () => [] }, assertActive() {}, beforeRequest, event: (event) => events.push(event)
    });
    expect(fixture.requests).toHaveLength(0);
    expect(beforeRequest).not.toHaveBeenCalled();
    expect(execute).not.toHaveBeenCalled();
    expect(events.filter((event) => event.type === 'text').map((event) => event.value.text))
      .toContain('The rule was observed, not a permanent guarantee.');
    const beforeContinue = await readFile(destination, 'utf8');
    expect(beforeContinue.startsWith(original)).toBe(true);
    await session.prompt('Explicitly continue Task B using recorded evidence.');
    expect(fixture.requests).toHaveLength(1);
    expect(beforeRequest).toHaveBeenCalledOnce();
    expect(execute).not.toHaveBeenCalled();
    const sent = fixture.requests[0]!.messages.map(fixtureMessageText).join('\n');
    expect(sent).toContain('TCP 8080');
    expect(sent).toContain('Task B: inspect the service without repeating Task A.');
    expect(sent).toContain('Current connection generation requires backend verification.');
    expect(sent).not.toContain('Obsolete connection generation: old-1');
    const saved = await readFile(destination, 'utf8');
    expect(saved.startsWith(original)).toBe(true);
    expect(saved).toContain('Historical observation: TCP 8080 rule exists.');
    expect(saved).not.toContain('synthetic-upgrade-key');
  } finally { session?.dispose(); await fixture.close(); await rm(root, { recursive: true, force: true }); }
});
