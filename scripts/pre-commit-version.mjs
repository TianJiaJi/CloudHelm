import { lstat, readFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import process from 'node:process';
import console from 'node:console';
import {
  README_FILE, VERSION_FILE, PACKAGE_FILES, SEMVER_PATTERN, buildSyncedFiles, findInconsistencies, parseVersionFile
} from './set-version.mjs';
import { CHANGELOG_FILE, hasVersionEntry, withDefaultEntry } from './changelog.mjs';
import { createGitIo } from './version-hook-index.mjs';
import { captureCleanFiles, mirrorCleanFiles } from './version-hook-worktree.mjs';
export { createGitIo } from './version-hook-index.mjs';

/**
 * Non-version commits are read-only. Version commits derive every generated byte
 * from the selected index snapshot, not from private working-tree drafts.
 * Clean working files are mirrored separately; dirty files remain untouched.
 */
export const SYNC_FILES = [...PACKAGE_FILES, README_FILE];
export function resolveHookDecision({ versionStaged, diskProblems, indexProblems }) {
  if (versionStaged) return { action: 'sync' };
  const problems = [...new Set([...(diskProblems ?? []), ...(indexProblems ?? [])])];
  return problems.length ? { action: 'block', problems } : { action: 'pass' };
}

async function regularText(root, file) {
  const target = path.join(root, file), stat = await lstat(target);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('版本检查需要普通文件');
  return readFile(target, 'utf8');
}
export async function readSyncTexts(root) {
  const packageTexts = new Map();
  for (const file of PACKAGE_FILES) packageTexts.set(file, await regularText(root, file));
  return { packageTexts, readmeText: await regularText(root, README_FILE) };
}
function checkedProblems(version, packages, readme) {
  for (const [file, text] of packages) {
    let value;
    try { value = JSON.parse(text)?.version; } catch { throw new Error(`版本文件格式无效：${file}`); }
    if (typeof value !== 'string' || !SEMVER_PATTERN.test(value)) throw new Error(`版本字段格式无效：${file}`);
  }
  return findInconsistencies(version, packages, readme);
}
const packagesOf = (texts) => new Map(PACKAGE_FILES.map((file) => [file, texts.get(file)]));
const stopped = (problems) => ({ action: 'block', problems, rewritten: [], staged: [], preserved: [], changelogDefault: false });

/** Index updates are one guarded batch; working-tree mirroring is not a Git/FS transaction. */
export async function runHook(root, overrides = {}) {
  const git = createGitIo(root, overrides);
  const before = new Map();
  for (const file of [VERSION_FILE, ...SYNC_FILES]) before.set(file, await git.indexText(file));
  let version, workingVersion;
  try {
    version = parseVersionFile(before.get(VERSION_FILE));
    workingVersion = parseVersionFile(await regularText(root, VERSION_FILE));
  } catch { return stopped(['version.json 的工作区或暂存内容格式无效']); }
  if (workingVersion !== version) return stopped(['version.json 的工作区与暂存版本不同，请确认要提交的版本']);
  const indexProblems = checkedProblems(version, packagesOf(before), before.get(README_FILE));
  const versionStaged = (await git.stagedFiles()).includes(VERSION_FILE);
  if (!versionStaged) {
    const disk = await readSyncTexts(root);
    const decision = resolveHookDecision({ versionStaged, indexProblems,
      diskProblems: checkedProblems(version, disk.packageTexts, disk.readmeText) });
    return { ...decision, version, problems: decision.problems ?? [], rewritten: [], staged: [], preserved: [], changelogDefault: false };
  }

  const after = buildSyncedFiles(version, packagesOf(before), before.get(README_FILE));
  const problems = checkedProblems(version, packagesOf(after), after.get(README_FILE));
  if (problems.length) return stopped(problems);
  const changelog = await git.indexText(CHANGELOG_FILE, true);
  const changelogDefault = changelog !== undefined && !hasVersionEntry(changelog, version);
  if (changelog !== undefined) {
    before.set(CHANGELOG_FILE, changelog);
    after.set(CHANGELOG_FILE, changelogDefault ? withDefaultEntry(changelog, version) : changelog);
  }
  const staged = [...after].filter(([file, text]) => text !== before.get(file)).map(([file]) => file);
  const dirty = new Set(await git.dirtyFiles([...after.keys()]));
  const captured = await captureCleanFiles(root, before, after, dirty);
  // Includes unchanged version.json and synchronization files as full preimage
  // guards. A conflicting index edit rejects the entire patch, not just a hunk.
  await git.applyPatch(before, after);
  const worktree = await mirrorCleanFiles(root, after, captured);
  return { action: 'sync', version, problems: [], staged, changelogDefault, ...worktree };
}

async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const result = await runHook(root);
  if (result.action === 'block') {
    for (const problem of result.problems) console.error(problem);
    console.error('版本检查未通过，提交已阻止；请检查所选版本与暂存内容，不要为绕过检查而整体暂存私有草稿。');
    process.exitCode = 1; return;
  }
  if (result.action !== 'sync') return;
  if (result.changelogDefault) console.log(`pre-commit 已在暂存区补齐默认更新日志：${CHANGELOG_FILE}`);
  if (result.staged.length) console.log(`pre-commit 已同步暂存版本：${result.staged.join('、')}`);
  if (result.rewritten.length) console.log(`pre-commit 已同步无未暂存改动的工作文件：${result.rewritten.join('、')}`);
  if (result.preserved.length) console.warn(`pre-commit 保留了工作区内容：${result.preserved.join('、')}；本地版本或日志如需同步，请手动合并，仅暂存要提交的部分。`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await main().catch(() => {
    // Native Git/JSON diagnostics may echo file contents; never forward them.
    console.error('版本同步未完成，提交已阻止；请检查暂存文件格式、合并冲突和索引锁。');
    process.exitCode = 1;
  });
}
